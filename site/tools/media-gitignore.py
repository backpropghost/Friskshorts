"""Rewrites site/.gitignore so git only tracks the web-ready media the pages reference
(same rule as tools/build.sh). PNG masters, full-sound Shorts and unused captures stay local.
Run from site/ after changing which media the pages use: python3 tools/media-gitignore.py"""
import pathlib, re
site = pathlib.Path(__file__).resolve().parent.parent
text = ""
for f in list(site.glob("*.html")) + list(site.glob("*/index.html")) + [site / "css/site.css", site / "js/site.js"]:
    text += f.read_text()
refs = sorted(set(re.findall(r"media/[A-Za-z0-9_@./-]+\.[a-z0-9]+", text)))
keep = ["media/MANIFEST.md", "media/CREDITS.md", "media/data/credits.json", "media/reel.json"]
lines = [".review/", ".DS_Store", "", "# Media: track only what the site uses (generated by tools/media-gitignore.py)",
         "/media/**", "!/media/**/"] + [f"!/{r}" for r in keep + refs if (site / r).exists()]
(site / ".gitignore").write_text("\n".join(lines) + "\n")
print(f"{len(refs)} referenced media files tracked")
